#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
source "${SCRIPT_DIR}/.env"
# Canonical CSP shared by every SDEE3 frontend (spec 05).
source "/Users/stefandjokic/Developer/identity/shared/clerk-csp.sh"

DIST_DIR="${DIST_DIR:-frontend/dist}"
if [[ "${DIST_DIR}" != /* ]]; then
  DIST_DIR="${ROOT_DIR}/${DIST_DIR}"
fi

if [[ -z "${DISTRIBUTION_ID:-}" ]]; then
  echo "ERROR: DISTRIBUTION_ID missing in scripts/.env" >&2
  exit 1
fi
if [[ ! -f "${SCRIPT_DIR}/../frontend/.env.production" ]]; then
  true
fi

write_production_env() {
  local dist_env="${ROOT_DIR}/frontend/.env.production"
  cat > "${dist_env}" <<EOF
# Generated by scripts/deploy-frontend.sh — do not hand-edit.
VITE_APP_ORIGIN=${VITE_APP_ORIGIN:?set VITE_APP_ORIGIN in scripts/.env}
VITE_CONVEX_URL=${VITE_CONVEX_URL:?set VITE_CONVEX_URL in scripts/.env}
VITE_CLERK_PUBLISHABLE_KEY=${VITE_CLERK_PUBLISHABLE_KEY:?set VITE_CLERK_PUBLISHABLE_KEY in scripts/.env}
VITE_IDENTITY_CONVEX_URL=${VITE_IDENTITY_CONVEX_URL:?set VITE_IDENTITY_CONVEX_URL in scripts/.env}
VITE_CLERK_SIGN_IN_URL=https://identity.sdee3.com/sign-in
VITE_CLERK_SIGN_UP_URL=https://identity.sdee3.com/sign-up
EOF
}

echo "=== Building frontend (production env from scripts/.env) ==="
write_production_env
pnpm --dir "${ROOT_DIR}/frontend" build --mode production

if [[ ! -f "${DIST_DIR}/index.html" ]]; then
  echo "ERROR: Missing ${DIST_DIR}/index.html" >&2
  exit 1
fi

echo ""
echo "=== Uploading hashed assets (long-lived cache) ==="
aws s3 sync "${DIST_DIR}" "s3://${BUCKET}" \
  --delete \
  --region "${REGION}" \
  --exclude "index.html" \
  --cache-control "public,max-age=31536000,immutable"

echo ""
echo "=== Uploading HTML shell (never edge-cached) ==="
aws s3 cp "${DIST_DIR}/index.html" "s3://${BUCKET}/index.html" \
  --region "${REGION}" \
  --content-type "text/html" \
  --cache-control "no-cache,no-store,must-revalidate"

echo ""
echo "=== Invalidating the distribution ==="
aws cloudfront create-invalidation \
  --distribution-id "${DISTRIBUTION_ID}" \
  --region "${REGION}" \
  --paths "/*" >/dev/null

echo ""
echo "=== Deploy complete ==="
echo "https://ezaudit.sdee3.com (identity: no-cache | assets+static: immutable)"
